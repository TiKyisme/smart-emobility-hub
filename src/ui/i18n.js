export const SUPPORTED_LANGUAGES = Object.freeze(Object.keys(TEXT));

export function normalizeLanguage(language) {
  return SUPPORTED_LANGUAGES.includes(language) ? language : InterfaceLanguage.VI;
}

export function hasText(key) {
  return Object.hasOwn(TEXT.en, key);
}

export function textKeys(language) {
  return Object.keys(TEXT[normalizeLanguage(language)]);
}

export function t(language, key, params = {}) {
  const entry = TEXT[normalizeLanguage(language)][key] ?? TEXT.en[key];
  if (entry === undefined) return key;
  if (typeof entry === "function") return entry(params);
  return entry.replace(/\{(\w+)\}/g, (match, name) => (params[name] === undefined ? match : String(params[name])));
}

export function formatTime(language, value) {
  if (!value) return t(language, "time.atStartup");
  return new Date(value).toLocaleTimeString(LOCALES[normalizeLanguage(language)], {
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
  });
}

export function formatDuration(language, milliseconds) {
  const seconds = Math.round(milliseconds / 1000);
  return seconds % 60 === 0
    ? t(language, "duration.minutes", { n: seconds / 60 })
    : t(language, "duration.seconds", { n: seconds });
}

// mm:ss (or h:mm:ss) for hold countdowns; never negative.
export function formatCountdown(milliseconds) {
  const total = Math.max(0, Math.ceil(milliseconds / 1000));
  const pad = (value) => String(value).padStart(2, "0");
  const hours = Math.floor(total / 3600);
  const minutes = Math.floor((total % 3600) / 60);
  const seconds = total % 60;
  return hours > 0 ? `${hours}:${pad(minutes)}:${pad(seconds)}` : `${pad(minutes)}:${pad(seconds)}`;
}

// Renders a service result / simulator update / simulation note in the selected language.
// Parameters whose name ends in "At" are ISO timestamps and are shown as local clock time.
export function describe(language, result) {
  if (!result) return "";
  const key = `result.${result.code}`;
  if (!result.code || !hasText(key)) return result.message ?? "";
  const params = Object.fromEntries(
    Object.entries(result.params ?? {}).map(([name, value]) => [name, name.endsWith("At") ? formatTime(language, value) : value]),
  );
  return t(language, key, params);
}

export function statusLabel(language, status) {
  const key = `status.${status}`;
  return hasText(key) ? t(language, key) : String(status ?? "").replaceAll("_", " ");
}
